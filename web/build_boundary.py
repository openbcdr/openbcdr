"""Embed only the explicitly public generic deny-list."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    lines = (ROOT / "config/boundary_patterns.txt").read_text(encoding="utf-8-sig").splitlines()
    patterns = [s.strip() for s in lines if s.strip() and not s.strip().startswith("#")]
    js = "// Generated by web/build_boundary.py. Generic public protection only.\n"
    js += "(function(root){'use strict';\nconst patterns=" + json.dumps(patterns, ensure_ascii=False) + ";\n"
    js += '''
// Python re whitespace includes control separators and NEL, but excludes BOM.
const ws='[\\\\t-\\\\r\\\\x1c-\\\\x20\\\\x85\\\\u00a0\\\\u1680\\\\u2000-\\\\u200a\\\\u2028\\\\u2029\\\\u202f\\\\u205f\\\\u3000]';
const compiled=patterns.map(p=>new RegExp(p.split('\\\\s').join(ws),'i'));
class BoundaryViolation extends Error { constructor(message) { super(message); this.name='BoundaryViolation'; } }
function scan(text,mode,attested=false) {
  if(!['sandbox','internal'].includes(mode)) throw new TypeError("mode must be one of ('sandbox', 'internal'), got '"+mode+"'");
  const matches=patterns.filter((p,i)=>compiled[i].test(text));
  const allowed=matches.length===0 && (mode==='internal'||attested);
  const reason=allowed?'clear':matches.length?'matched deny-list: '+[...new Set(matches)].sort().join(', '):'sandbox mode requires an explicit synthetic/sanitized attestation';
  return {allowed,mode,matches,attested,missing_local:false,reason};
}
function enforce(text,mode,attested=false) {
  const res=scan(text,mode,attested);
  if(!res.allowed) throw new BoundaryViolation('['+mode+' mode] refused: '+res.reason);
  return res;
}
const api={patterns,MODES:['sandbox','internal'],BoundaryViolation,scan,enforce};
if(typeof module==='object' && module.exports) module.exports=api;
if(root) root.OpenBCDR_BOUNDARY=api;
})(typeof window!=='undefined'?window:null);
'''
    (ROOT / "web/boundary.js").write_text(js, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
