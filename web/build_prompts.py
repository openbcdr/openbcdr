"""Copy public prompt literals and Pydantic schemas without loading runtime config."""
import ast
import json
import re
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from openbcdr.models import PlanExtract, CoverageBatch


def literal(path, name):
    tree = ast.parse((ROOT / path).read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == name for t in node.targets):
            return ast.literal_eval(node.value)
    raise ValueError(name)


def main():
    data = dict(EXTRACTION_SYSTEM=literal("openbcdr/ingest.py", "SYSTEM"),
                COMPLIANCE_SYSTEM=literal("openbcdr/analyzers/compliance.py", "SYSTEM"),
                ORG_CONTEXT=literal("openbcdr/config.py", "ORG_CONTEXT"),
                REQUIREMENTS_PER_CALL=literal("openbcdr/config.py", "REQUIREMENTS_PER_CALL"),
                PLAN_EXTRACT_SCHEMA=PlanExtract.model_json_schema(),
                COVERAGE_BATCH_SCHEMA=CoverageBatch.model_json_schema())
    js = "// Generated by web/build_prompts.py. SYSTEM strings are copied verbatim.\n"
    js += "(function(root){'use strict';\nconst api=" + json.dumps(data, ensure_ascii=False, indent=2) + ";\n"
    js += '''
const schemaBlock = schema => "Return ONLY a JSON object matching this schema:\\n" + JSON.stringify(schema, null, 2);
api.buildExtractionInput = function(planText, planIdHint = "") {
  return api.EXTRACTION_SYSTEM + api.ORG_CONTEXT + "\\n\\n" + schemaBlock(api.PLAN_EXTRACT_SCHEMA)
    + "\\n\\nExtract the structured record from this plan document.\\n"
    + (planIdHint ? "Use plan_id " + planIdHint + " if the document does not state one.\\n" : "")
    + "\\n<plan_document>\\n" + planText + "\\n</plan_document>";
};
api.buildComplianceInput = function(planText, requirementBatch) {
  const block = r => "req_id: " + r.req_id + "\\nsource: " + r.source + " " + r.section
    + "\\nmandatory: " + (r.mandatory === false ? "no" : "yes") + "\\nrequirement: " + r.requirement;
  return api.COMPLIANCE_SYSTEM + api.ORG_CONTEXT + "\\n\\n<plan_document>\\n" + planText + "\\n</plan_document>\\n\\n"
    + "Assess the plan document against these " + requirementBatch.length
    + " requirements. Return exactly one finding per requirement.\\n\\n"
    + requirementBatch.map(block).join("\\n\\n---\\n\\n") + "\\n\\n" + schemaBlock(api.COVERAGE_BATCH_SCHEMA);
};
if(typeof module==='object' && module.exports) module.exports=api;
if(root) root.OpenBCDR_PROMPTS=api;
})(typeof window!=='undefined'?window:null);
'''
    (ROOT / "web/prompts.js").write_text(js, encoding="utf-8", newline="\n")
    # Keep engine.js usable on its own, without a prompts.js dependency.
    engine = ROOT / "web/engine.js"
    text = engine.read_text(encoding="utf-8")
    text = re.sub(r"const PLAN_SCHEMA = /\* PLAN_SCHEMA \*/.*?;", lambda _: "const PLAN_SCHEMA = /* PLAN_SCHEMA */ " + json.dumps(data["PLAN_EXTRACT_SCHEMA"], ensure_ascii=False) + ";", text, count=1, flags=re.S)
    engine.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
