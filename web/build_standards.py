"""Generate browser data from the three explicitly public indexes, offline."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from openbcdr.models import Requirement

NAMES = ("ffiec-bcm-2019", "finra-4370", "nist-800-34r1")


def main():
    records = []
    seen = set()
    for name in NAMES:
        data = json.loads((ROOT / "standards" / (name + ".json")).read_text(encoding="utf-8"))
        for record in data["requirements"] if isinstance(data, dict) else data:
            r = Requirement(**record)
            if r.req_id in seen:
                raise ValueError("duplicate req_id in standards index: " + r.req_id)
            seen.add(r.req_id)
            records.append(r.model_dump(mode="json"))
    output = "// Generated by web/build_standards.py; public indexes only.\n"
    output += "(function(root){ const data = " + json.dumps(records, ensure_ascii=False, indent=2)
    output += ";\nif(typeof module==='object' && module.exports) module.exports=data;\n"
    output += "if(root) root.OpenBCDR_STANDARDS=data;\n})(typeof window!=='undefined'?window:null);\n"
    (ROOT / "web" / "standards.js").write_text(output, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
